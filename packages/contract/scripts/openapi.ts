// Emits docs/openapi.yaml from src/routes.ts. CI fails if the committed file is stale.
// A tiny YAML emitter keeps the contract package dependency-free.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { componentSchemas, pathParams, routes } from '../src/routes.ts';

type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

function scalar(value: string | number | boolean | null): string {
  if (typeof value !== 'string') return String(value);
  return /^[A-Za-z0-9_./-]+$/.test(value) && !/^(true|false|null|\d+)$/.test(value)
    ? value
    : JSON.stringify(value);
}

// Empty collections must stay explicit: `security: []` means "public", a bare key means null.
function inline(value: Json): string | null {
  if (Array.isArray(value)) return value.length ? null : '[]';
  if (value !== null && typeof value === 'object') return Object.keys(value).length ? null : '{}';
  return scalar(value);
}

function toYaml(value: Json, indent = 0): string {
  const pad = '  '.repeat(indent);
  if (Array.isArray(value)) {
    return value
      .map((item) => {
        const flat = inline(item);
        return flat !== null ? `${pad}- ${flat}\n` : `${pad}-\n${toYaml(item, indent + 1)}`;
      })
      .join('');
  }
  if (value !== null && typeof value === 'object') {
    return Object.entries(value)
      .map(([key, item]) => {
        const flat = inline(item);
        return flat !== null
          ? `${pad}${scalar(key)}: ${flat}\n`
          : `${pad}${scalar(key)}:\n${toYaml(item, indent + 1)}`;
      })
      .join('');
  }
  return `${pad}${scalar(value)}\n`;
}

const STATUS_TEXT: Record<number, string> = { 200: 'OK', 201: 'Created', 204: 'No Content' };

const paths: Record<string, Record<string, Json>> = {};
const schemas: Record<string, Json> = { ...(componentSchemas as Record<string, Json>) };

for (const route of routes) {
  // A route may reference a component schema by name (no inline `schema`) instead of redefining it.
  if (route.requestBody) schemas[route.requestBody.schemaName] = route.requestBody.schema as Json;
  if (route.response.schema && route.response.schemaName) {
    schemas[route.response.schemaName] = route.response.schema as Json;
  }
  paths[route.path] ??= {};
  paths[route.path]![route.method] = {
    summary: route.summary,
    ...(pathParams(route.path).length
      ? {
          parameters: pathParams(route.path).map((name): Json => ({
            name,
            in: 'path',
            required: true,
            schema: name === 'id' || name === 'user_id' ? { type: 'string', format: 'uuid' } : { type: 'string' },
          })),
        }
      : {}),
    ...(route.public ? { security: [] } : {}),
    ...(route.requestBody
      ? {
          requestBody: {
            required: true,
            content: {
              'application/json': {
                schema: { $ref: `#/components/schemas/${route.requestBody.schemaName}` },
              },
            },
          },
        }
      : {}),
    responses: {
      [String(route.response.status)]: {
        description: STATUS_TEXT[route.response.status] ?? 'OK',
        ...(route.response.schemaName
          ? {
              content: {
                'application/json': {
                  schema: { $ref: `#/components/schemas/${route.response.schemaName}` },
                },
              },
            }
          : {}),
      },
    },
  };
}

const doc: Json = {
  openapi: '3.1.0',
  info: { title: 'AbodeNestly API', version: '0.0.0' },
  security: [{ bearerAuth: [] }],
  paths,
  components: {
    securitySchemes: { bearerAuth: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' } },
    schemas,
  },
};

const out = fileURLToPath(new URL('../../../docs/openapi.yaml', import.meta.url));
writeFileSync(out, `# Generated by packages/contract/scripts/openapi.ts — do not edit.\n${toYaml(doc)}`);
console.log(`wrote ${out}`);
